/* 按科目+难度分桶（出题时 O(1) 取） */
var NEW_BY_KEY = {};
(function () {
  NEW_BANK.forEach(function (it) {
    var k = it.s + '_' + it.d;
    if (!NEW_BY_KEY[k]) NEW_BY_KEY[k] = [];
    NEW_BY_KEY[k].push(it);
  });
})();

/* 某关可用的题目池：关卡 → 难度（1-4关 d1 / 5-10 d2 / 11-14 d3 / 15-17 d4）
   若指定科目+难度没题，回退到同难度的其它科目，再回退到全部新题 */
function stageDiff(id) { return id <= 4 ? 1 : (id <= 10 ? 2 : (id <= 14 ? 3 : 4)); }
function poolForStage(stage, subject) {
  var d = stageDiff(stage);
  var key = subject + '_' + d;
  if (NEW_BY_KEY[key] && NEW_BY_KEY[key].length) return NEW_BY_KEY[key];
  var any = [];
  Object.keys(NEW_BY_KEY).forEach(function (k) {
    if (parseInt(k.split('_')[1], 10) === d) any = any.concat(NEW_BY_KEY[k]);
  });
  return any.length ? any : NEW_BANK;
}
